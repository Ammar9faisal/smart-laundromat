-- Baseline: machines and profiles
--
-- These two tables were originally created in the shared Supabase project
-- through the dashboard. This file records them so the schema can be rebuilt
-- from scratch (local Supabase, a separate test project, or final submission).
--
-- Every statement is guarded, so running this file against the shared project
-- leaves the existing tables, policies and signup trigger as they are. The only
-- possible change there: if row level security happens to be off on one of the
-- tables, it is turned on, and if that table has no policies yet, a read policy
-- matching the current behaviour is added.

create table if not exists public.machines (
    id bigint generated by default as identity primary key,
    type text not null,
    capacity integer not null,
    price numeric not null,
    status text not null default 'AVAILABLE',
    active boolean not null default true
);

create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    full_name text,
    role text not null default 'customer',
    created_at timestamptz not null default now()
);

alter table public.machines enable row level security;
alter table public.profiles enable row level security;

do $baseline$
begin
    -- Read access policies, only when the table has no policies yet.
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'machines'
    ) then
        create policy "Anyone can view machines"
            on public.machines
            for select
            to anon, authenticated
            using (true);
    end if;

    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'profiles'
    ) then
        create policy "Users can view own profile"
            on public.profiles
            for select
            to authenticated
            using (id = (select auth.uid()));
    end if;

    -- Create a customer profile for every new Supabase Auth user. Skipped when
    -- auth.users already has a trigger (the shared project already has one).
    if not exists (
        select 1
        from pg_trigger t
        join pg_class c on c.oid = t.tgrelid
        join pg_namespace n on n.oid = c.relnamespace
        where n.nspname = 'auth'
          and c.relname = 'users'
          and not t.tgisinternal
    ) then
        create or replace function public.handle_new_user()
        returns trigger
        language plpgsql
        security definer
        set search_path = ''
        as $fn$
        begin
            insert into public.profiles (id, full_name, role)
            values (new.id, new.raw_user_meta_data ->> 'full_name', 'customer');
            return new;
        end;
        $fn$;

        create trigger on_auth_user_created
            after insert on auth.users
            for each row execute function public.handle_new_user();
    end if;
end;
$baseline$;
